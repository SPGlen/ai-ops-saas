import { test, expect } from "@playwright/test";
const enabled=process.env.E2E_SHOWCASE==="1";
test.describe("企业演示验收",()=>{
  test.skip(!enabled,"仅在独立企业演示数据库上执行");
  test("负责人可直接体验经营成果、票据与内容案例",async({page})=>{
    const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
    await page.goto("/");
    await page.getByRole("button",{name:"机构负责人",exact:true}).click();
    await expect(page.getByRole("heading",{name:"一个工作台，看清一家机构的经营"})).toBeVisible();
    await expect(page.getByText("30.0%",{exact:false})).toBeVisible();
    await expect(page.getByRole("link",{name:"数字人直播（增值）",exact:true})).toHaveCount(0);
    await page.screenshot({path:"../docs/screenshots/showcase-overview.png",fullPage:true});
    await page.getByRole("button",{name:"播放视频案例",exact:false}).click();
    const video=page.locator("video");await expect(video).toBeVisible();
    await video.evaluate(async el=>{await (el as HTMLVideoElement).play();});
    await expect.poll(()=>video.evaluate(el=>(el as HTMLVideoElement).currentTime)).toBeGreaterThan(.2);
    await page.getByRole("link",{name:"财务台账",exact:true}).first().click();
    await expect(page.getByText("实收",{exact:true}).first()).toBeVisible();
    await page.screenshot({path:"../docs/screenshots/showcase-finance.png",fullPage:true});
    await page.locator("#financial-transactions tbody tr").filter({hasText:"教室场地费"}).getByRole("button",{name:"查看票据与详情",exact:true}).click();
    const dialog=page.getByRole("dialog");await expect(dialog.getByText("票据原件",{exact:true})).toBeVisible();
    await expect.poll(()=>dialog.locator("img").first().evaluate((el:any)=>el.complete&&el.naturalWidth>0)).toBe(true);
    await dialog.screenshot({path:"../docs/screenshots/showcase-receipt.png"});
    await dialog.getByRole("button",{name:"关闭",exact:true}).click();
    await page.getByRole("link",{name:"学员档案",exact:true}).first().click();
    await expect(page.getByText("启蒙创想 · 周六上午班",{exact:false}).first()).toBeVisible();
    await expect(page.getByRole("columnheader",{name:"家长手机号",exact:true}).first()).toBeVisible();
    const phones=await page.locator(".class-roster .phone-number").allTextContents();
    expect(phones.length).toBeGreaterThan(0);
    expect(phones.every(p=>/^\d{11}$/.test(p))).toBe(true);
    await page.screenshot({path:"../docs/screenshots/showcase-students.png",fullPage:true});
    await page.getByRole("link",{name:"自媒体矩阵",exact:true}).first().click();
    await expect(page.getByRole("table").getByText("青禾AI · 中心校区 · 亲子创作",{exact:true})).toBeVisible();
    await expect(page.getByText("未连接",{exact:true}).first()).toBeVisible();
    await page.screenshot({path:"../docs/screenshots/showcase-matrix.png",fullPage:true});
    await page.getByRole("link",{name:"社群运营",exact:true}).first().click();
    await expect(page.getByText("周末AI亲子体验预热",{exact:true})).toBeVisible();
    await page.getByRole("link",{name:"表单与流程",exact:true}).first().click();
    await expect(page.getByText("演示 · 周末体验活动申请表",{exact:true})).toBeVisible();
    await page.goto("/#addons");
    await expect(page.getByRole("heading",{name:"数字人直播",exact:false})).toHaveCount(0);
    expect(errors).toEqual([]);
  });
  test("切换授课岗位后，入口与数据范围同时收缩",async({page})=>{
    await page.goto("/");await page.getByRole("button",{name:"授课",exact:true}).click();
    await expect(page.getByRole("heading",{name:"一个工作台，看清一家机构的经营"})).toBeVisible();
    await expect(page.getByRole("link",{name:"财务台账",exact:true})).toHaveCount(0);
    await expect(page.getByRole("link",{name:"自媒体矩阵",exact:true})).toHaveCount(0);
    await page.getByRole("link",{name:"学员档案",exact:true}).first().click();
    await expect(page.getByText("启蒙创想 · 周六上午班",{exact:false}).first()).toBeVisible();
    await expect(page.getByText("AI探索 · 周日下午班",{exact:true})).toHaveCount(0);
    await page.screenshot({path:"../docs/screenshots/showcase-teacher.png",fullPage:true});
    await page.getByLabel("切换演示岗位").selectOption("finance.qinghe@zhiying.example");
    await expect(page.getByRole("link",{name:"财务台账",exact:true}).first()).toBeVisible();
    await expect(page.getByRole("link",{name:"教务管理",exact:true})).toHaveCount(0);
  });
  test("移动端可进入演示、切换身份并查看成品",async({page})=>{
    await page.setViewportSize({width:390,height:844});await page.goto("/");
    await page.getByRole("button",{name:"机构负责人",exact:true}).click();
    await expect(page.getByRole("heading",{name:"一个工作台，看清一家机构的经营"})).toBeVisible();
    await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await page.screenshot({path:"../docs/screenshots/showcase-mobile.png",fullPage:true});
  });
});
